/**
 * Visible product branding: U·SKOP (middle dot U+00B7).
 */
import { describe, expect, it } from "vitest"
import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"

import { messages } from "@/i18n/messages"
import { PRODUCT_NAME, PRODUCT_NAME_SEPARATOR } from "@/shared/brand"
import { repoRoot } from "@/test-utils/repoRoot"
import { readAppSource } from "@/test-utils/appSource"
import { readMessagesSource } from "@/test-utils/messagesSource"

function readSrc(rel: string): string {
  return readFileSync(join(repoRoot, rel), "utf8")
}

describe("product brand U·SKOP", () => {
  it("canonical visible name is U·SKOP with middle dot U+00B7", () => {
    expect(PRODUCT_NAME).toBe("U·SKOP")
    expect(PRODUCT_NAME_SEPARATOR).toBe("\u00B7")
    expect(PRODUCT_NAME).toContain(PRODUCT_NAME_SEPARATOR)
    expect(PRODUCT_NAME.indexOf(PRODUCT_NAME_SEPARATOR)).toBe(1)
    expect(PRODUCT_NAME.codePointAt(1)).toBe(0x00b7)
    // Reject common substitutes.
    expect(PRODUCT_NAME).not.toContain("-")
    expect(PRODUCT_NAME).not.toContain(".")
    expect(PRODUCT_NAME).not.toContain("•")
    expect(PRODUCT_NAME).not.toBe("USKOP")
    expect(PRODUCT_NAME).not.toBe("WIT")
  })

  it("NO and EN both expose identical product brand", () => {
    expect(messages.no.results.pdfBrandName).toBe(PRODUCT_NAME)
    expect(messages.en.results.pdfBrandName).toBe(PRODUCT_NAME)
    expect(messages.no.results.pdfBrandName).toBe(messages.en.results.pdfBrandName)
    expect(messages.no.results.pdfFooter).toBe(`Generert av ${PRODUCT_NAME}`)
    expect(messages.en.results.pdfFooter).toBe(`Generated by ${PRODUCT_NAME}`)
    expect(messages.no.results.pdfShareLinkAnchorText).toContain(PRODUCT_NAME)
    expect(messages.en.results.pdfShareLinkAnchorText).toContain(PRODUCT_NAME)
  })

  it("header wordmark and footers use PRODUCT_NAME (no user-facing WIT)", () => {
    const wordmark = readSrc("src/shared/BrandWordmark.tsx")
    expect(wordmark).toContain("PRODUCT_NAME")
    expect(wordmark).not.toMatch(/\bWIT\b/)
    // Wordmark is upright — italic only remains on the subtitle via not-italic.
    const nameClass = wordmark.slice(
      wordmark.indexOf("font-heading"),
      wordmark.indexOf("{PRODUCT_NAME}"),
    )
    expect(nameClass).toContain("font-heading")
    expect(nameClass).toContain("text-[1.6875rem]")
    expect(nameClass).toContain("font-semibold")
    expect(nameClass).toContain("tracking-tight")
    expect(nameClass).not.toMatch(/\bitalic\b/)

    for (const rel of [
      "src/app/App.tsx",
      "src/features/analysis-library/AnalysisLibraryPage.tsx",
    ] as const) {
      const src = rel === "src/app/App.tsx" ? readAppSource() : readSrc(rel)
      expect(src).toContain("PRODUCT_NAME")
      expect(src).toContain("BrandWordmark")
      expect(src).toMatch(/© 2026 \{PRODUCT_NAME\}/)
      expect(src).not.toMatch(/\bWIT\b/)
    }
  })

  it("public / pre-auth surfaces do not expose U·SKOP (app/PDF still do)", () => {
    for (const rel of [
      "src/app/LandingPage.tsx",
      "src/app/LoginPage.tsx",
      "src/app/LoginCard.tsx",
    ] as const) {
      const src = readSrc(rel)
      expect(src).not.toMatch(/<BrandWordmark\b/)
      expect(src).not.toContain("PRODUCT_NAME")
      expect(src).not.toContain("U·SKOP")
      expect(src).not.toContain("USKOP")
      expect(src).not.toMatch(/\bWIT\b/)
      expect(src).not.toContain("working title")
      expect(src).not.toMatch(/© 2026 \{PRODUCT_NAME\}/)
      expect(src).not.toMatch(/© 2026 U·SKOP/)
    }

    const landing = readSrc("src/app/LandingPage.tsx")
    expect(landing).toContain("© 2026")
    expect(landing).not.toMatch(/© 2026 \$\{PRODUCT_NAME\}/)

    // Auth copy stays neutral (no product name).
    expect(messages.no.auth.title).not.toContain(PRODUCT_NAME)
    expect(messages.en.auth.title).not.toContain(PRODUCT_NAME)
    expect(messages.no.auth.helper).not.toContain(PRODUCT_NAME)
    expect(messages.en.auth.helper).not.toContain(PRODUCT_NAME)

    // Authenticated app surfaces still branded.
    expect(readAppSource()).toContain("BrandWordmark")
    expect(readSrc("src/features/analysis-library/AnalysisLibraryPage.tsx")).toContain(
      "BrandWordmark",
    )
    expect(messages.no.results.pdfBrandName).toBe(PRODUCT_NAME)
    expect(messages.en.results.pdfBrandName).toBe(PRODUCT_NAME)
    expect(PRODUCT_NAME).toBe("U·SKOP")
  })

  it("PDF branding uses PRODUCT_NAME / message brand strings", () => {
    expect(messages.no.results.pdfBrandName).toBe(PRODUCT_NAME)
    expect(messages.en.results.pdfBrandName).toBe(PRODUCT_NAME)
    const panel =
      readSrc("src/features/results/ResultsPanel.tsx") +
      readSrc("src/features/results/pdfExport.tsx")
    expect(panel).toContain('brandName: t("results.pdfBrandName")')
    expect(panel).toContain('brandName={t("results.pdfBrandName")}')
    expect(panel).not.toMatch(/\bWIT\b/)
  })

  it("Noto Sans PDF font file is present for middle-dot rendering", () => {
    const regular = join(repoRoot, "src/pdf/fonts/NotoSans-Regular.ttf")
    expect(existsSync(regular)).toBe(true)
    // Latin-1 Supplement includes U+00B7; NotoSans registers this TTF for PDF.
    const fonts = readSrc("src/pdf/pdfFonts.ts")
    expect(fonts).toContain("NotoSans-Regular.ttf")
    expect(fonts).toContain('family: "NotoSans"')
  })

  it("browser document title is not leftover WIT branding", () => {
    const html = readSrc("index.html")
    expect(html).not.toMatch(/\bWIT\b/)
    // Current title is a technical app id, not the old product brand.
    expect(html).toContain("<title>cost-simulator</title>")
  })

  it("no user-facing WIT brand strings remain in src messages / brand surfaces", () => {
    const messagesSrc = readMessagesSource()
    expect(messagesSrc).not.toMatch(/"WIT"/)
    expect(messagesSrc).not.toMatch(/'WIT'/)
    expect(messagesSrc).not.toMatch(/ i WIT/)
    expect(messagesSrc).not.toMatch(/ in WIT/)
    expect(messagesSrc).not.toMatch(/av WIT/)
    expect(messagesSrc).not.toMatch(/by WIT/)

    const brand = readSrc("src/shared/brand.ts")
    expect(brand).toContain('PRODUCT_NAME = "U·SKOP"')
    expect(brand).not.toMatch(/\bWIT\b/)
  })

  it("technical package/storage identifiers are unchanged (not renamed for brand)", () => {
    const pkg = JSON.parse(readSrc("package.json")) as { name: string }
    expect(pkg.name).toBe("cost-simulator")
    // Representative persistence keys must not have been rewritten for the brand.
    const localRepo = readSrc("src/persistence/localAnalysisLibraryRepository.ts")
    expect(localRepo).not.toMatch(/U·SKOP|USKOP|U-SKOP/)
  })
})
